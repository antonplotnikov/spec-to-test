"""Typed models of the QA Agent: test plans, runs, results and bug reports.

A plan case holds declarative steps (`PlanStep`), never code. The executor
interprets a fixed set of actions; a case runs only while its approval
fingerprint still matches its content, so editing an approved case revokes
the approval.
"""

import hashlib
import json
from enum import StrEnum

from pydantic import BaseModel, Field

from spec_to_test.models import Severity

PLAN_SCHEMA_VERSION = 1
RUN_SCHEMA_VERSION = 1
MAX_TEXT = 2000
MAX_TARGET = 300
MAX_VALUE = 1000


class StepAction(StrEnum):
    GOTO = "goto"
    FILL = "fill"
    CLICK = "click"
    SELECT = "select"
    CHECK = "check"
    UNCHECK = "uncheck"
    PRESS = "press"
    WAIT_FOR = "wait_for"
    EXPECT_VISIBLE = "expect_visible"
    EXPECT_HIDDEN = "expect_hidden"
    EXPECT_TEXT = "expect_text"
    EXPECT_NO_TEXT = "expect_no_text"
    EXPECT_URL = "expect_url"
    EXPECT_TITLE = "expect_title"
    EXPECT_VALUE = "expect_value"


ASSERTIONS = frozenset({
    StepAction.EXPECT_VISIBLE, StepAction.EXPECT_HIDDEN, StepAction.EXPECT_TEXT, StepAction.EXPECT_NO_TEXT,
    StepAction.EXPECT_URL, StepAction.EXPECT_TITLE, StepAction.EXPECT_VALUE,
})
# What each action needs: (target, value). "optional" means either form is valid.
VALUE_ONLY = frozenset({StepAction.GOTO, StepAction.EXPECT_URL, StepAction.EXPECT_TITLE})
TARGET_ONLY = frozenset({
    StepAction.CLICK, StepAction.CHECK, StepAction.UNCHECK, StepAction.WAIT_FOR,
    StepAction.EXPECT_VISIBLE, StepAction.EXPECT_HIDDEN,
})
TARGET_AND_VALUE = frozenset({StepAction.FILL, StepAction.SELECT, StepAction.EXPECT_VALUE})
OPTIONAL_TARGET = frozenset({StepAction.EXPECT_TEXT, StepAction.EXPECT_NO_TEXT, StepAction.PRESS})


RISK_SUBMITS_FORM = "submits_form"


class PlanStep(BaseModel):
    action: StepAction
    # Locator such as "label=Email", "role=button[name=Sign in]", "text=Welcome", "#id".
    target: str = Field(default="", max_length=MAX_TARGET)
    # Text to type, option, key, URL/path or expected text. "{{secret:NAME}}" types a configured secret.
    value: str = Field(default="", max_length=MAX_VALUE)

    @property
    def is_assertion(self) -> bool:
        return self.action in ASSERTIONS


class CaseOrigin(StrEnum):
    TEST_CASE = "test_case"  # converted from a workspace test case
    MANUAL = "manual"  # written on the QA Agent page
    AI = "ai"  # steps proposed by an LLM, to be reviewed
    IMPORTED = "imported"  # from a plan JSON file
    DISCOVERY = "discovery"  # generated by Autonomous QA from what was observed on the website


class PlanCase(BaseModel):
    id: str = Field(min_length=1, max_length=40)
    requirement_id: str = Field(min_length=1, max_length=80)
    test_case_id: str = Field(default="", max_length=80)
    title: str = Field(min_length=1, max_length=300)
    steps: list[PlanStep] = Field(default_factory=list)
    expected_result: str = Field(default="", max_length=MAX_TEXT)
    origin: CaseOrigin = CaseOrigin.MANUAL
    # Source steps that could not be turned into executable steps (shown, never guessed).
    unparsed: list[str] = Field(default_factory=list)
    # Set when the case has a consequence beyond reading pages (RISK_SUBMITS_FORM: it submits
    # a form, which may send a message). Such a case runs only when the run allows it.
    risk: str = Field(default="", max_length=40)
    approved: bool = False
    approved_fingerprint: str = ""
    approved_at: str = ""

    def fingerprint(self) -> str:
        content = {
            "requirement_id": self.requirement_id,
            "title": self.title,
            "steps": [s.model_dump(mode="json") for s in self.steps],
            "expected_result": self.expected_result,
        }
        if self.risk:  # only when set, so approvals made before this field existed stay valid
            content["risk"] = self.risk
        return hashlib.sha256(json.dumps(content, sort_keys=True).encode()).hexdigest()[:16]

    @property
    def is_approved(self) -> bool:
        """Approved, and not edited since."""
        return self.approved and self.approved_fingerprint == self.fingerprint()

    @property
    def has_assertion(self) -> bool:
        return any(step.is_assertion for step in self.steps)


class TestPlan(BaseModel):
    __test__ = False  # not a pytest class

    schema_version: int = PLAN_SCHEMA_VERSION
    document_hash: str = ""
    target_url: str = Field(default="", max_length=2048)
    created_at: str = ""
    updated_at: str = ""
    cases: list[PlanCase] = Field(default_factory=list)

    def case(self, case_id: str) -> PlanCase | None:
        return next((c for c in self.cases if c.id == case_id), None)


class RunStatus(StrEnum):
    PASSED = "passed"
    FAILED = "failed"
    BLOCKED = "blocked"
    NOT_RUN = "not_run"


class StepResult(BaseModel):
    index: int
    step: PlanStep
    status: RunStatus
    error: str = ""
    duration_ms: int = 0


class CaseResult(BaseModel):
    case_id: str
    requirement_id: str
    test_case_id: str = ""
    title: str
    status: RunStatus
    # Why it did not pass: a qaagent.reason.<code> key suffix, with parameters.
    reason: str = ""
    reason_params: dict[str, str] = Field(default_factory=dict)
    error: str = ""
    expected_result: str = ""
    actual_result: str = ""
    steps: list[StepResult] = Field(default_factory=list)
    # File name inside the run folder ("" when no screenshot was taken, or
    # executor.SCREENSHOT_WITHHELD when the page showed a secret value).
    screenshot: str = ""
    final_url: str = ""
    console_errors: list[str] = Field(default_factory=list)
    blocked_requests: list[str] = Field(default_factory=list)
    started_at: str = ""
    duration_ms: int = 0

    @property
    def failed_step(self) -> StepResult | None:
        return next((s for s in self.steps if s.status != RunStatus.PASSED), None)


class BugReport(BaseModel):
    id: str = Field(min_length=1)
    run_id: str
    case_id: str
    requirement_id: str
    test_case_id: str = ""
    title: str = Field(min_length=1, max_length=300)
    severity: Severity = Severity.MEDIUM
    steps_to_reproduce: list[str] = Field(default_factory=list)
    expected: str = ""
    actual: str = ""
    error: str = ""
    evidence: list[str] = Field(default_factory=list)
    environment: dict[str, str] = Field(default_factory=dict)
    # Autonomous QA: "defect" or "uncertain_expectation" (see qa_agent.triage); "" for manual runs.
    classification: str = ""
    created_at: str = ""


class RunState(StrEnum):
    RUNNING = "running"
    COMPLETED = "completed"
    ABORTED = "aborted"


class QARun(BaseModel):
    schema_version: int = RUN_SCHEMA_VERSION
    id: str = Field(pattern=r"^[0-9a-f]{16}$")
    document_hash: str = ""
    document_title: str = ""
    target_url: str
    created_at: str = ""
    finished_at: str = ""
    state: RunState = RunState.RUNNING
    # The person confirmed they may test this URL and approved this run.
    authorized: bool = False
    allow_destructive: bool = False
    # Cases with a risk (they submit forms) were allowed to run.
    allow_forms: bool = False
    # Set for a retest: the run whose failed cases were run again.
    parent_run_id: str = ""
    browser: str = ""
    limits: dict[str, int] = Field(default_factory=dict)
    # The cases as they were when the run started (plans change afterwards).
    cases: list[PlanCase] = Field(default_factory=list)
    results: list[CaseResult] = Field(default_factory=list)
    bugs: list[BugReport] = Field(default_factory=list)
    error: str = ""

    def result(self, case_id: str) -> CaseResult | None:
        return next((r for r in self.results if r.case_id == case_id), None)

    def counts(self) -> dict[str, int]:
        return {status.value: sum(r.status == status for r in self.results) for status in RunStatus}

    def case(self, case_id: str) -> PlanCase | None:
        return next((c for c in self.cases if c.id == case_id), None)
