def test_failed_run_gets_exactly_one_repair_with_failure_context(tmp_path):
    agent = FakeAgent(*explore_then_submit(good_script("Save")),
                      [tool_use("r1", "browser_snapshot")],
                      [tool_use("r2", "submit_test_script", **good_script("Save password"))])
    runner = FakeRunner(failed_run(), passed_run())
    job, statuses = run(tmp_path, agent, runner)
    assert job.status == JobStatus.PASSED and job.reason == "passed_after_repair"
    assert job.repair_attempted and len(job.runs) == 2 and len(runner.runs) == 2
    repair = agent.requests[3]["messages"][-1]["content"]
    assert repair[0]["type"] == "tool_result" and repair[0]["tool_use_id"] == "t4"  # the submit call is answered first
    assert "Timeout 15000ms" in repair[-1]["text"] and "exactly one repair attempt" in repair[-1]["text"]
    assert "Save password" in runner.runs[1]["code"]


def test_repair_may_not_change_assertions(tmp_path):
    weakened = good_script("Save password")
    weakened["steps"][-1].update(action="expect_visible", value="")
    agent = FakeAgent(*explore_then_submit(good_script("Save")),
                      [tool_use("r1", "submit_test_script", **weakened)],
                      [tool_use("r2", "submit_test_script", **good_script("Save password"))])
    job, _ = run(tmp_path, agent, FakeRunner(failed_run(), passed_run()))
    assert "changed what the test asserts" in agent.tool_results(4)[0]["content"]
    assert job.status == JobStatus.PASSED
    assert job.assertion_checks[0].value == "Link expired"


