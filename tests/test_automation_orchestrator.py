def test_relative_navigation_is_resolved_and_offsite_navigation_refused(tmp_path):
    browsers = []

    def factory(*args):
        browser = browser_factory()(*args)
        browsers.append(browser)
        return browser

    agent = FakeAgent(
        [tool_use("a", "browser_navigate", url="/reset"), tool_use("b", "browser_navigate", url="http://169.254.169.254/")],
        [tool_use("c", "submit_test_script", **good_script())],
    )
    job, _ = run(tmp_path, agent, browser=factory)
    assert browsers[0].calls == [("browser_navigate", {"url": "https://staging.example.com/reset"})]
    refused = agent.tool_results(1)[1]
    assert refused["is_error"] and "Navigation refused" in refused["content"]
    assert job.tool_calls == 1 and browsers[0].closed


def test_destructive_click_is_refused_by_snapshot_name_unless_allowed(tmp_path):
    turns = lambda: [  # noqa: E731
        [tool_use("s", "browser_snapshot")],
        [tool_use("d", "browser_click", element="the red button", target="e5")],  # e5 = "Delete account"
        [tool_use("t", "submit_test_script", **good_script())],
    ]
    agent = FakeAgent(*turns())
    job, _ = run(tmp_path, agent)
    result = agent.tool_results(2)[0]
    assert result["is_error"] and "destructive" in result["content"]
    assert any(e.code == "destructive_refused" for e in job.events)

    allowed = FakeAgent(*turns())
    run(tmp_path / "b", allowed, allow_destructive=True)
    assert not allowed.tool_results(2)[0].get("is_error")


def test_rejected_script_gets_feedback_and_can_be_resubmitted(tmp_path):
    bad = good_script()
    bad["steps"][-1]["evidence"] = "made up"
    agent = FakeAgent([tool_use("a", "submit_test_script", **bad)], [tool_use("b", "submit_test_script", **good_script())])
